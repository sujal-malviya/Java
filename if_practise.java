import java.util.*;
public class if_practise {
    public static void main(String[] args) {
        Scanner in = new Scanner (System.in);
        int n = in.nextInt();
        if(n>0)
        {
            System.out.println(n+" is positive.");
        }
        else{
            System.out.println(n+" is negative.");
        }
    }
}
